import { chromium, devices } from 'playwright';
import { preview } from 'vite';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const server = await preview({ base: '/SAA/', preview: { host: '127.0.0.1', port: 4187, strictPort: true } });
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined });
  const context = await browser.newContext({ ...devices['iPhone 13'], defaultBrowserType: undefined });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:4187/SAA/');
  const nav = name => page.getByRole('navigation').getByRole('button', { name, exact: true }).click();
  const openGame = () => page.getByRole('button', { name: '設計クエストを遊ぶ →', exact: true }).click();
  const choose = async name => page.getByRole('button', { name, exact: false }).click();
  await openGame();
  await page.getByRole('button', { name: '工房の設計をはじめる →' }).click();
  assert.equal(await page.getByRole('button', { name: 'この構成をテストする →' }).isDisabled(), true);
  await choose('EC2 × 1');
  await page.getByRole('button', { name: 'この構成をテストする →' }).click();
  await page.getByRole('heading', { name: 'あと一歩。構成を見直そう。' }).waitFor();
  await page.getByRole('button', { name: 'カードを選び直す' }).click();
  await choose('S3 / 非公開バケット');
  await choose('必要な権限のIAMロール');
  await page.getByRole('button', { name: 'この構成をテストする →' }).click();
  await page.getByRole('heading', { name: '✓ ミッションクリア！' }).waitFor();
  await page.getByRole('button', { name: '次のミッションへ →' }).click();
  await choose('EC2 × 2 / 別々のAZ');
  await nav('設定');
  await page.getByRole('button', { name: '教材を保存・オフライン状態を確認', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'オフライン準備完了' }).waitFor({ timeout: 60000 });
  await context.setOffline(true);
  await page.reload();
  await openGame();
  await page.getByRole('heading', { name: 'ひとつのAZが止まったら？' }).waitFor();
  assert.equal(await page.getByRole('button', { name: /EC2 × 2 \/ 別々のAZ/ }).getAttribute('aria-pressed'), 'true');
  for (const name of ['Application Load Balancer', 'S3 / 非公開バケット', '必要な権限のIAMロール']) await choose(name);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/game-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'この構成をテストする →' }).click();
  await page.getByRole('heading', { name: '✓ ミッションクリア！' }).waitFor();
  await page.getByRole('button', { name: '次のミッションへ →' }).click();
  for (const name of ['S3 / 非公開バケット', '必要な権限のIAMロール', 'フェデレーション + MFA']) await choose(name);
  await page.getByRole('button', { name: 'この構成をテストする →' }).click();
  await page.getByRole('button', { name: '工房の完成を見る →' }).click();
  await page.getByRole('heading', { name: /工房を守る、\s*設計ができた。/ }).waitFor();
  assert.match(await page.locator('.quest-score').innerText(), /8\s*\/ 9 STARS/);
  await page.getByRole('button', { name: 'もう一度、設計する' }).click();
  await page.getByRole('button', { name: 'キャンセル', exact: true }).click();
  await page.reload();
  await openGame();
  await page.getByRole('heading', { name: /工房を守る、\s*設計ができた。/ }).waitFor();
  await page.getByRole('button', { name: '関連テキストを読む →' }).first().click();
  await page.getByRole('heading', { name: '要件から構成を選ぶ' }).waitFor();
  await nav('今日'); await openGame();
  await page.getByRole('button', { name: 'もう一度、設計する' }).click();
  await page.getByRole('button', { name: 'ゲーム記録をリセットして開始' }).click();
  await page.getByRole('heading', { name: '消えない成果を届ける' }).waitFor();
  assert.equal(await page.locator('.quest-card[aria-pressed=true]').count(), 0);
  await page.setViewportSize({ width: 320, height: 568 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('PASS: /SAA/ subpath; mobile card selection; failed design/retry; all 3 missions; stars; offline reload/resume; completion persistence; lesson link; reset/cancel; 320px layout. Chromium emulation, not physical iPhone.');
} finally {
  await browser?.close();
  await new Promise(resolve => server.httpServer.close(resolve));
}
